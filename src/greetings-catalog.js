import { t } from "./i18n.js";

export const greetingSource =
  "https://science.nasa.gov/mission/voyager/golden-record-contents/greetings/";
export const normalizeSearch = (value) =>
  value
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/[đĐ]/g, "d")
    .toLocaleLowerCase()
    .trim();
export function filterGreetings(query = "", country = "") {
  const tokens = normalizeSearch(query).split(/\s+/).filter(Boolean);
  return greetings.filter(
    (g) =>
      (!country || g.countries.includes(country)) &&
      tokens.every((token) =>
        normalizeSearch(
          [g.language, t(g.language), g.region, t(g.region), ...g.countries, ...g.countries.map((name) => t(name)), ...g.aliases].join(" "),
        ).includes(token),
      ),
  );
}
